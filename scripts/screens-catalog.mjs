#!/usr/bin/env node
/* npm run catalog  — writes SCREENS.md: every screen of this console for people and AI tools.
   Sources (both in this repository, so the catalog never depends on a website):
     .claude/skills/lepide-design-system/prototype/screens.json  — the 55 captured screens (facts + screenshots)
     flows/<id>/flow.json                                         — flows documented step by step (e.g. Active Directory)
   `--check` fails when SCREENS.md is out of date instead of writing it (used by `npm run check:ai`). */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG = '.claude/skills/lepide-design-system/prototype';
const cat = JSON.parse(readFileSync(join(root, CATALOG, 'screens.json'), 'utf8'));
const flows = readdirSync(join(root, 'flows'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, 'flows', d.name, 'flow.json')))
  .map((d) => ({ dir: `flows/${d.name}`, ...JSON.parse(readFileSync(join(root, 'flows', d.name, 'flow.json'), 'utf8')) }));

const code = (s) => '`' + s + '`';
const list = (xs) => xs.map(code).join(' · ');
const src = (p) => (existsSync(join(root, p)) ? `[${code(p)}](${p})` : code(p) + ' (not in this repository)');
/* A flow owns the screens under its routes: the catalog entry links to the flow page. */
const flowFor = (path) => flows.find((f) => f.routes?.some((r) => path === r.path));

const out = [];
out.push('# Screens', '');
out.push('Every screen of this Lepide console prototype: where it is, what is on it, the code that draws it and a screenshot.',
  '**Generated by `npm run catalog` — do not edit by hand.** Read it before building or changing a screen, then build',
  'the screen like the screenshot with the Lepide Design System ([AGENTS.md](AGENTS.md)).', '');
out.push('- **Live demo:** https://lepide-new-ui-gray.vercel.app — add a path below to open that screen (any e-mail and password sign in).',
  '- **Run it locally:** `npm install && npm run dev` → http://localhost:5175. Paths below are routes of that app.',
  '- **Screenshots** are in this repository (captured at 1440 × 900, light theme), so this page works without any website.',
  `- **Design system:** [spec](.claude/skills/lepide-design-system/DESIGN.md) · live https://lepide-new-ds.vercel.app/DESIGN.md ·`,
  '  MCP https://lepide-new-ds.vercel.app/mcp', '');

out.push('## Flows documented step by step', '');
out.push('| Flow | Steps and dialogs | Docs |', '|---|---|---|');
for (const f of flows) {
  const steps = f.wizard?.steps?.map((s) => s.label) ?? [];
  const dialogs = f.dialogs?.map((d) => d.title) ?? [];
  out.push(`| **${f.title}** | ${[...steps, ...dialogs.map((d) => `dialog “${d}”`)].join(' → ')} | [FLOW.md](${f.dir}/FLOW.md) · [flow.json](${f.dir}/flow.json) |`);
}
out.push('');

out.push('## How the code is organised', '');
out.push('| Area | Read first |', '|---|---|');
for (const [area, doc] of [['Modules (Auditor, Trust, Detect, Protect, Identify, My Lepide, Dashboards)', 'src/modules/BUILDING.md'],
  ['Settings (frame and one folder per category)', 'src/settings/BUILDING.md'], ['Report library (hub, view, builder)', 'src/reports/README.md']]) {
  if (existsSync(join(root, doc))) out.push(`| ${area} | [${code(doc)}](${doc}) |`);
}
out.push('| UI components | `src/ui/index.ts` re-exports `@lepide/ds-react` — use only these |', '');

const modules = [...new Set(cat.screens.map((s) => s.module))];
out.push('## All screens', '');
out.push(modules.map((m) => `[${m}](#${m.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')})`).join(' · '), '');
for (const m of modules) {
  out.push(`### ${m}`, '');
  for (const s of cat.screens.filter((x) => x.module === m)) {
    const title = s.crumbs?.length > 1 ? s.crumbs.join(' › ') : s.title || s.path;
    out.push(`#### ${title}`, '');
    out.push(`![${title.replace(/[[\]]/g, '')}](${CATALOG}/${s.screenshot})`, '');
    const rows = [`- **Route** ${code(s.path)} · **Code** ${src(s.source)}`];
    const f = flowFor(s.path);
    if (f) rows.push(`- **Flow** [${f.title}](${f.dir}/FLOW.md)`);
    if (s.description) rows.push(`- **Description** ${s.description}`);
    if (s.patterns?.length) rows.push(`- **Patterns** ${s.patterns.join(', ')}`);
    if (s.actions?.length) rows.push(`- **Header actions** ${s.actions.map((a) => (a.primary ? `**${a.label}** (primary)` : a.label)).join(' · ')}`);
    if (s.tabs?.length) rows.push(`- **Tabs** ${list(s.tabs)}`);
    if (s.sectionNav?.length) rows.push(`- **Section nav** ${s.sectionNav.slice(0, 20).join(' · ')}`);
    if (s.tableColumns?.length) rows.push(`- **Table columns** ${s.tableColumns.join(' · ')}`);
    if (s.cards?.length) rows.push(`- **Cards** ${s.cards.join(' · ')}`);
    if (s.primaryFlow) rows.push(`- **Primary action opens** ${typeof s.primaryFlow === 'string' ? s.primaryFlow : `${s.primaryFlow.opens ?? 'view'} “${s.primaryFlow.title}”${s.primaryFlow.steps?.length ? ` (steps: ${s.primaryFlow.steps.join(' → ')})` : ''}${s.primaryFlow.fields?.length ? `; fields: ${s.primaryFlow.fields.join(', ')}` : ''}`}${s.primaryFlow.screenshot ? ` ([screenshot](${CATALOG}/${s.primaryFlow.screenshot}))` : ''}`);
    if (s.reachedFrom) rows.push(`- **Reached from** ${typeof s.reachedFrom === 'string' ? code(s.reachedFrom) : JSON.stringify(s.reachedFrom)}`);
    out.push(...rows, '');
  }
}
for (const f of flows) {
  out.push(`### ${f.title} (flow)`, '');
  for (const sc of [...(f.screens ?? []), ...(f.wizard?.steps ?? []), ...(f.dialogs ?? [])]) {
    const name = sc.title || sc.label;
    if (!sc.screenshot) continue;
    out.push(`#### ${name}`, '', `![${name}](${f.dir}/${sc.screenshot})`, '', `- **Flow** [${f.title}](${f.dir}/FLOW.md) · **Code** ${src(f.code.wizard)}`, '');
  }
}
const text = out.join('\n').replace(/\n{3,}/g, '\n\n');

if (process.argv.includes('--check')) {
  const cur = existsSync(join(root, 'SCREENS.md')) ? readFileSync(join(root, 'SCREENS.md'), 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) { console.error('SCREENS.md is out of date: run `npm run catalog`.'); process.exit(1); }
  console.log(`SCREENS.md is up to date (${cat.screens.length} screens, ${flows.length} flow(s)).`);
} else {
  writeFileSync(join(root, 'SCREENS.md'), text);
  console.log(`SCREENS.md: ${cat.screens.length} screens, ${flows.length} flow(s).`);
}
